"""Install, remove, export and check the AltStack Desktop skills and Claude Code plugin.

Rules this module keeps:
* It only runs when the user asks (the `amerika-claude` CLI or the Settings button). No package script calls it.
* It only ever writes below the given home, in exactly these places: ~/.claude/skills/amerika-*/ (skills),
  ~/.claude/plugins/amerika-marketplace/ (a local plugin marketplace holding the amerika-os plugin),
  ~/.local/state/amerika-os/claude-install.json (manifest) and ~/.local/state/amerika-os/claude-backup/<time>/ (backups).
* It never overwrites a folder it did not create (no `.amerika-managed` marker): it refuses and changes nothing.
* `remove` deletes exactly the files recorded in the manifest, and keeps any file the user edited afterwards.
"""
import hashlib
import io
import json
import os
import re
import shutil
import time
import zipfile
from pathlib import Path

from . import __version__

MARKER = '.amerika-managed'
MARKER_TEXT = 'amerika-os claude skills; created by amerika-claude, safe to remove with: amerika-claude remove\n'
MARKETPLACE = 'amerika-marketplace'
PLUGIN = 'amerika-os'
MCP_COMMAND = os.environ.get('AMERIKA_MCP_COMMAND', '/usr/bin/amerika-mcp')
STUDIO_MCP_COMMAND = os.environ.get('AMERIKA_STUDIO_MCP_COMMAND', '/usr/bin/amerika-studio-mcp')
INSTRUCTIONS_MARK = '<!-- amerika-os custom instructions (generated by amerika-claude export) -->'
COMMANDS_MARK = '<!-- amerika-os commands cheat sheet (generated by amerika-claude export) -->'
ZIP_TIME = (2026, 1, 1, 0, 0, 0)  # fixed, so exports are reproducible


class InstallError(Exception):
    """A refusal or failure with a message fit for the user. Nothing was changed."""


# ---------------------------------------------------------------------------------------------- locations
def source_dir():
    """The plugin source: AMERIKA_CLAUDE_SHARE/plugin/amerika-os, the source tree, or /usr/share/amerika-claude."""
    candidates = []
    if os.environ.get('AMERIKA_CLAUDE_SHARE'):
        candidates.append(Path(os.environ['AMERIKA_CLAUDE_SHARE']) / 'plugin' / PLUGIN)
    candidates.append(Path(__file__).resolve().parent.parent / 'plugin' / PLUGIN)
    candidates.append(Path('/usr/share/amerika-claude/plugin') / PLUGIN)
    for c in candidates:
        if (c / '.claude-plugin' / 'plugin.json').is_file():
            return c
    raise InstallError('The Amerika Claude plugin files were not found. Install the amerika-claude package.')


def paths(home=None):
    home = Path(home) if home else Path.home()
    state = home / '.local/state/amerika-os'
    return {'home': home, 'skills': home / '.claude/skills', 'market': home / '.claude/plugins' / MARKETPLACE,
            'state': state, 'manifest': state / 'claude-install.json', 'backups': state / 'claude-backup'}


# ---------------------------------------------------------------------------------------------- skills
def parse_frontmatter(text):
    """Minimal, strict parser for the SKILL.md / command frontmatter: single-line `key: value` pairs between --- lines."""
    lines = text.split('\n')
    if not lines or lines[0].strip() != '---':
        raise ValueError('missing frontmatter')
    meta = {}
    for i, line in enumerate(lines[1:], 1):
        if line.strip() == '---':
            return meta, '\n'.join(lines[i + 1:])
        if not line.strip():
            continue
        m = re.fullmatch(r'([A-Za-z][A-Za-z0-9_-]*):\s*(.*)', line)
        if not m:
            raise ValueError(f'bad frontmatter line: {line!r}')
        value = m.group(2).strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in '"\'':
            value = value[1:-1]
        meta[m.group(1)] = value
    raise ValueError('frontmatter is not closed')


def installed_name(name):
    """Skills are installed (and exported) with an amerika- prefix so they can never collide with the user's own."""
    return name if name.startswith('amerika-') else 'amerika-' + name


def list_skills(src=None):
    src = Path(src) if src else source_dir()
    out = []
    for d in sorted((src / 'skills').iterdir()):
        md = d / 'SKILL.md'
        if not md.is_file():
            continue
        meta, _ = parse_frontmatter(md.read_text(encoding='utf-8'))
        out.append({'name': meta.get('name', d.name), 'dir': d, 'description': meta.get('description', ''),
                    'installed_name': installed_name(d.name)})
    return out


def skill_files(skill):
    """{relative path: bytes} for one skill, with the frontmatter name rewritten to the installed name."""
    files = {}
    for f in sorted(skill['dir'].rglob('*')):
        if f.is_file() and '__pycache__' not in f.parts:
            rel = f.relative_to(skill['dir']).as_posix()
            data = f.read_bytes()
            if rel == 'SKILL.md':
                text = data.decode('utf-8')
                text = re.sub(r'(?m)^name:.*$', f'name: {skill["installed_name"]}', text, count=1)
                data = text.encode('utf-8')
            files[rel] = data
    return files


def plugin_files(src=None, studio=None):
    """{relative path: bytes} of the marketplace tree: marketplace.json plus the plugin (.mcp.json filtered to what is installed)."""
    src = Path(src) if src else source_dir()
    if studio is None:
        studio = os.path.exists(STUDIO_MCP_COMMAND)
    files = {}
    for f in sorted(src.rglob('*')):
        if not f.is_file() or '__pycache__' in f.parts:
            continue
        rel = f.relative_to(src).as_posix()
        data = f.read_bytes()
        if rel == '.mcp.json':
            cfg = json.loads(data)
            cfg['mcpServers']['amerika']['command'] = MCP_COMMAND
            if 'amerika-studio' in cfg['mcpServers']:
                if studio:
                    cfg['mcpServers']['amerika-studio']['command'] = STUDIO_MCP_COMMAND
                else:
                    del cfg['mcpServers']['amerika-studio']
            data = (json.dumps(cfg, indent=2) + '\n').encode()
        files[f'plugins/{PLUGIN}/{rel}'] = data
    meta = json.loads((src / '.claude-plugin/plugin.json').read_text())
    market = {'name': PLUGIN, 'owner': {'name': 'AltStack Desktop'},
              'metadata': {'description': 'Local marketplace created by amerika-claude. Remove with: amerika-claude remove'},
              'plugins': [{'name': meta['name'], 'source': f'./plugins/{PLUGIN}', 'description': meta['description'],
                           'version': meta['version']}]}
    files['.claude-plugin/marketplace.json'] = (json.dumps(market, indent=2) + '\n').encode()
    return files


def _sha(data):
    return hashlib.sha256(data).hexdigest()


def _read_manifest(p):
    try:
        return json.loads(p['manifest'].read_text())
    except (OSError, ValueError):
        return None


def _owned(directory):
    return (directory / MARKER).is_file() and not directory.is_symlink()


def _plan(p, want_skills, want_plugin, src):
    """Compute the targets: [{kind, root, files}]. Raises InstallError on conflicts before anything is written."""
    targets = []
    if want_skills:
        for skill in list_skills(src):
            targets.append({'kind': 'skill', 'name': skill['installed_name'], 'root': p['skills'] / skill['installed_name'],
                            'files': skill_files(skill)})
    if want_plugin:
        targets.append({'kind': 'plugin', 'name': MARKETPLACE, 'root': p['market'], 'files': plugin_files(src)})
    conflicts = []
    for t in targets:
        root = t['root']
        if root.is_symlink() or (root.exists() and not root.is_dir()):
            conflicts.append(f'{root} exists and is not a folder created by Amerika')
        elif root.exists() and not _owned(root):
            conflicts.append(f'{root} already exists and was not created by Amerika')
    if conflicts:
        raise InstallError('Refusing to overwrite files that are not Amerika\'s. Nothing was changed.\n  ' + '\n  '.join(conflicts))
    for t in targets:
        t['files'][MARKER] = MARKER_TEXT.encode()
    return targets


def _differs(target):
    root = target['root']
    for rel, data in target['files'].items():
        f = root / rel
        if not f.is_file() or f.read_bytes() != data:
            return True
    # stale managed files from an older version also count as a difference
    if root.is_dir():
        have = {f.relative_to(root).as_posix() for f in root.rglob('*') if f.is_file()}
        if have - set(target['files']):
            return True
    return False


def _backup(p, targets, stamp):
    """Copy the managed targets that are about to change (older Amerika versions) and the manifest. Returns the backup dir."""
    dest = p['backups'] / stamp
    n = 1
    while dest.exists():  # two installs in the same second
        n += 1
        dest = p['backups'] / f'{stamp}-{n}'
    dest.mkdir(parents=True, mode=0o700)
    saved = []
    for t in targets:
        if t['root'].is_dir() and _differs(t):
            rel = t['root'].relative_to(p['home'])
            shutil.copytree(t['root'], dest / rel, symlinks=False)
            saved.append(rel.as_posix())
    if p['manifest'].is_file():
        shutil.copy2(p['manifest'], dest / 'claude-install.json')
        saved.append('claude-install.json')
    (dest / 'backup.json').write_text(json.dumps({'created': stamp, 'saved': saved,
                                                  'note': 'Only Amerika-created files are ever replaced; nothing of yours is touched.'}, indent=2))
    return dest


def _write_target(p, t, created_dirs):
    root = t['root']
    keep = set(t['files'])
    if root.is_dir():  # replace an older managed copy
        for f in sorted(root.rglob('*'), reverse=True):
            if f.is_file() and f.relative_to(root).as_posix() not in keep:
                f.unlink()
    for rel, data in t['files'].items():
        f = root / rel
        for parent in reversed([x for x in f.parents if x != f and p['home'] in x.parents and not x.exists()]):
            created_dirs.append(parent)
        f.parent.mkdir(parents=True, exist_ok=True)
        tmp = f.with_name(f.name + '.amerika-tmp')
        tmp.write_bytes(data)
        tmp.replace(f)


def install(home=None, skills=True, plugin=True, src=None):
    """Install into `home`. Idempotent: an unchanged install writes nothing. Returns a report dict."""
    p = paths(home)
    src = Path(src) if src else source_dir()
    if not skills and not plugin:
        raise InstallError('Nothing to install.')
    targets = _plan(p, skills, plugin, src)
    old = _read_manifest(p) or {}
    changed = [t for t in targets if not t['root'].is_dir() or _differs(t)]
    # an older manifest may list targets that this run no longer installs (e.g. a removed skill): they are removed below
    wanted = {t['root'].relative_to(p['home']).as_posix() for t in targets}
    stale = [r for r in old.get('roots', []) if r not in wanted and (p['home'] / r).is_dir() and _owned(p['home'] / r)]
    if not changed and not stale and old:
        return {'changed': False, 'installed': sorted(t['name'] for t in targets), 'backup': None, 'next_steps': _next_steps(p, plugin)}
    stamp = time.strftime('%Y%m%d-%H%M%S')
    backup = _backup(p, targets, stamp)
    created = [p['home'] / c for c in old.get('created_dirs', [])]
    for r in stale:
        shutil.rmtree(p['home'] / r)
    new_dirs = []
    for t in targets:
        _write_target(p, t, new_dirs)
    created_rel = sorted({d.relative_to(p['home']).as_posix() for d in created + new_dirs})
    manifest = {'version': __version__, 'installed_at': time.strftime('%Y-%m-%dT%H:%M:%S%z'), 'home': str(p['home']),
                'roots': sorted(t['root'].relative_to(p['home']).as_posix() for t in targets),
                'files': {(t['root'] / rel).relative_to(p['home']).as_posix(): _sha(data) for t in targets for rel, data in t['files'].items()},
                'created_dirs': created_rel, 'backup': str(backup)}
    p['state'].mkdir(parents=True, exist_ok=True, mode=0o700)
    tmp = p['manifest'].with_name('claude-install.json.tmp')
    tmp.write_text(json.dumps(manifest, indent=2))
    tmp.replace(p['manifest'])
    return {'changed': True, 'installed': sorted(t['name'] for t in targets), 'backup': str(backup), 'next_steps': _next_steps(p, plugin)}


def _next_steps(p, plugin):
    steps = ['Restart Claude Desktop (or start a new Claude Code session) so it re-reads ~/.claude/skills.']
    if plugin:
        steps.append(f'Optional plugin (slash commands): in Claude Code run  /plugin marketplace add {p["market"]}  then  /plugin install {PLUGIN}@{PLUGIN}')
    return steps


def remove(home=None, force=False):
    """Delete exactly what the manifest lists. Files the user edited since are kept (unless force)."""
    p = paths(home)
    manifest = _read_manifest(p)
    if not manifest:
        return {'removed': 0, 'kept': [], 'installed': False}
    removed, kept = 0, []
    for rel, digest in manifest.get('files', {}).items():
        f = p['home'] / rel
        if f.is_symlink() or not f.is_file():
            continue
        if not force and _sha(f.read_bytes()) != digest:
            kept.append(rel)
            continue
        f.unlink()
        removed += 1
    dirs = {p['home'] / r for r in manifest.get('roots', [])} | {p['home'] / r for r in manifest.get('created_dirs', [])}
    for d in sorted(dirs, key=lambda x: len(x.parts), reverse=True):
        d = Path(d)
        if p['home'] not in d.parents or not d.is_dir() or d.is_symlink():
            continue
        # a managed root with only unmanaged leftovers stays; empty ones go
        try:
            d.rmdir()
        except OSError:
            pass
    if not kept:
        p['manifest'].unlink(missing_ok=True)
    return {'removed': removed, 'kept': kept, 'installed': True, 'backups': str(p['backups'])}


def status(home=None):
    p = paths(home)
    manifest = _read_manifest(p)
    try:
        skills = list_skills()
        available = True
    except InstallError:
        skills, available = [], False
    out = {'available': available, 'version': __version__, 'skills_available': [s['installed_name'] for s in skills],
           'installed': bool(manifest), 'installed_skills': [], 'plugin_installed': False, 'modified': [], 'missing': [],
           'outdated': False, 'manifest': str(p['manifest']), 'skills_dir': str(p['skills']), 'marketplace_dir': str(p['market'])}
    if manifest:
        for root in manifest.get('roots', []):
            if root.startswith('.claude/skills/'):
                out['installed_skills'].append(root.rsplit('/', 1)[1])
            elif root.endswith(MARKETPLACE):
                out['plugin_installed'] = True
        for rel, digest in manifest.get('files', {}).items():
            f = p['home'] / rel
            if not f.is_file():
                out['missing'].append(rel)
            elif _sha(f.read_bytes()) != digest:
                out['modified'].append(rel)
        out['installed_at'] = manifest.get('installed_at')
        out['backup'] = manifest.get('backup')
        out['outdated'] = manifest.get('version') != __version__ or (
            available and sorted(out['installed_skills']) != sorted(out['skills_available']) and bool(out['installed_skills']))
    return out


# ---------------------------------------------------------------------------------------------- export
def custom_instructions():
    guide = (source_dir().parent.parent.parent / 'AMERIKA.md')
    if not guide.is_file():
        guide = source_dir() / 'AMERIKA.md'
    rules = ('Paste this into Claude Desktop > Settings > Profile > custom instructions (or a Project\'s instructions).\n\n')
    body = (
        f'{INSTRUCTIONS_MARK}\n# AltStack Desktop\n\n{rules}---\n\n'
        'You are running on AltStack Desktop, a Linux desktop built around Claude. When the `amerika` MCP server is connected you can operate '
        'the computer with its tools (windows, apps, settings, notifications, files in the home folder, diagnostics). Rules:\n\n'
        '1. Look before you act: use read tools (system.status, windows.list, apps.list, settings.get) first, then make the smallest change.\n'
        '2. Never say something worked until a read tool confirms it. Report what you changed and how to undo it.\n'
        '3. Risky tools ask the user for approval; the user can press Stop at any time. If an action is declined, do not retry it unless asked.\n'
        '4. Stay inside the home folder. Never read or write keys, tokens, ~/.ssh, ~/.config, ~/.claude. Never print a secret you find.\n'
        '5. Prefer settings and the dedicated tools over shell.run; shell.run is critical and asks every time.\n'
        '6. Do not install software, change the update channel, power off or delete files unless the user clearly asked.\n'
        '7. If the amerika tools are missing, tell the user to log in to the AltStack Desktop session and press Connect in Settings > AI.\n\n'
        'The skills named amerika-* contain the detailed procedures; commands.md lists the slash commands (Claude Code plugin). The full operating manual follows.\n\n---\n\n')
    return body + (guide.read_text(encoding='utf-8') if guide.is_file() else '')


def export(dest, src=None):
    """Write one zip per skill (folder `amerika-<skill>/SKILL.md` inside) plus custom-instructions.md. Returns the file list."""
    dest = Path(dest)
    if dest.exists() and not dest.is_dir():
        raise InstallError(f'{dest} exists and is not a folder')
    ci = dest / 'custom-instructions.md'
    if ci.exists() and INSTRUCTIONS_MARK not in ci.read_text(encoding='utf-8', errors='replace'):
        raise InstallError(f'{ci} exists and was not written by Amerika; choose another folder')
    cs = dest / 'commands.md'
    if cs.exists() and COMMANDS_MARK not in cs.read_text(encoding='utf-8', errors='replace'):
        raise InstallError(f'{cs} exists and was not written by Amerika; choose another folder')
    dest.mkdir(parents=True, exist_ok=True)
    written = []
    for skill in list_skills(src):
        target = dest / f'{skill["installed_name"]}.zip'
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED) as z:
            for rel, data in skill_files(skill).items():
                info = zipfile.ZipInfo(f'{skill["installed_name"]}/{rel}', ZIP_TIME)
                info.external_attr = 0o644 << 16
                info.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(info, data)
        target.write_bytes(buf.getvalue())
        written.append(str(target))
    ci.write_text(custom_instructions(), encoding='utf-8')
    written.append(str(ci))
    sheet = Path(src) / 'commands.md' if src else source_dir() / 'commands.md'
    cs.write_text(COMMANDS_MARK + '\n' + (sheet.read_text(encoding='utf-8') if sheet.is_file() else '# AltStack Desktop commands\n'), encoding='utf-8')
    written.append(str(cs))
    return written


# ---------------------------------------------------------------------------------------------- doctor
def doctor(home=None):
    """A list of {name, state: ok|warn|fail, detail}. Read-only."""
    checks = []

    def add(name, state, detail):
        checks.append({'name': name, 'state': state, 'detail': detail})
    try:
        src = source_dir()
        skills = list_skills(src)
        add('plugin files', 'ok', f'{len(skills)} skills in {src}')
        bad = []
        for s in skills:
            meta, _ = parse_frontmatter((s['dir'] / 'SKILL.md').read_text(encoding='utf-8'))
            if not meta.get('name') or not meta.get('description'):
                bad.append(s['name'])
        add('skill frontmatter', 'fail' if bad else 'ok', ('invalid: ' + ', '.join(bad)) if bad else 'all skills have name and description')
    except (InstallError, ValueError) as error:
        add('plugin files', 'fail', str(error))
    st = status(home)
    if st['installed']:
        problems = st['missing'] + st['modified']
        add('installed skills', 'warn' if problems or st['outdated'] else 'ok',
            f'{len(st["installed_skills"])} skills installed' + (f'; changed or missing: {problems}' if problems else '')
            + ('; a newer version is available, run amerika-claude install' if st['outdated'] else ''))
        if st['plugin_installed'] and st['installed_skills']:
            add('duplicate skills', 'warn', 'Skills are installed both directly and via the plugin marketplace; if Claude lists them twice, '
                'use `amerika-claude remove` and install with --skills-only or --plugin-only.')
    else:
        add('installed skills', 'warn', 'not installed; run: amerika-claude install')
    add('amerika-mcp command', 'ok' if os.path.exists(MCP_COMMAND) else 'fail', MCP_COMMAND)
    try:
        from amerika import common
        from amerika.ai import connect
        conn = connect.status()
        add('Claude MCP connection', 'ok' if conn.get('claude') else 'warn',
            'the amerika MCP server is registered with Claude Desktop' if conn.get('claude') else 'not connected; press Connect in Settings > AI')
        sock = Path(common.CONTROL_SOCKET)
        add('shell broker', 'ok' if sock.exists() else 'warn', 'broker socket present' if sock.exists() else 'Amerika Shell is not running in this session')
    except Exception as error:  # noqa: BLE001 - a diagnosis must not crash
        add('Claude MCP connection', 'warn', f'could not check: {error}')
    add('claude CLI', 'ok' if shutil.which('claude') else 'warn', shutil.which('claude') or 'not on PATH (only needed for the plugin commands)')
    return checks
